/// Translate only application-owned stored notices/titles, never arbitrary user records.
pub fn stored_copy(value: &str, language: Language) -> String {
    Text::ALL
        .iter()
        .find(|m| {
            let (en, zh) = m.pair();
            value == en || value == zh
        })
        .map_or_else(|| value.to_owned(), |m| language.t(*m).to_owned())
}
