//! Sole compile-time English/Simplified Chinese interface catalog.
//! Protocol identifiers, user content and original technical diagnostics are never translated.
use serde::{Deserialize, Serialize};
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum Language {
    #[serde(rename = "en")]
    English,
    #[serde(rename = "zh-CN")]
    Chinese,
}
impl Language {
    pub fn code(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::Chinese => "zh-CN",
        }
    }
    pub fn system() -> Self {
        let locale = std::env::var("LC_ALL")
            .ok()
            .filter(|v| !v.is_empty())
            .or_else(|| std::env::var("LC_MESSAGES").ok().filter(|v| !v.is_empty()))
            .or_else(|| std::env::var("LANG").ok())
            .unwrap_or_default();
        if locale.to_ascii_lowercase().starts_with("zh") {
            Self::Chinese
        } else {
            Self::English
        }
    }
    pub fn t(self, message: Text) -> &'static str {
        let (en, zh) = message.pair();
        match self {
            Self::English => en,
            Self::Chinese => zh,
        }
    }
}
